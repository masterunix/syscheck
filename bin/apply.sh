#!/usr/bin/env bash
# Make the system match the settings: schedule (systemd timer), sudoers grant, login
# banner hook, logrotate, and ownership of the state directory.
# Root only. Run by install.sh and after every `syscheck set`.
set -uo pipefail
SC_PREFIX=/opt/syscheck
. "$SC_PREFIX/lib/common.sh"

[ "$(id -u)" = "0" ] || { echo "apply.sh must run as root" >&2; exit 1; }
fail=0

# --- schedule -----------------------------------------------------------------
# A systemd timer rather than cron: every systemd distribution has it, and with
# Persistent=true a run missed while the machine was off or asleep happens
# shortly after it comes back.
UNIT=/etc/systemd/system
rm -f /etc/cron.d/syscheck            # versions before 0.2 used cron
cat > "$UNIT/syscheck.service" <<U
# Generated by $SC_PREFIX/bin/apply.sh. Change settings with: syscheck settings
[Unit]
Description=syscheck daily health check
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=$SC_PREFIX/bin/run.sh
StandardOutput=append:/var/log/syscheck.log
StandardError=append:/var/log/syscheck.log
# The alarm detaches and must outlive the run that started it.
KillMode=process
TimeoutStartSec=4h
U
hh="${SC_SCHEDULE%%:*}"; mm="${SC_SCHEDULE##*:}"
if [[ "$hh" =~ ^[0-9]{1,2}$ ]] && [[ "$mm" =~ ^[0-9]{2}$ ]]; then
  cat > "$UNIT/syscheck.timer" <<U
# Generated by $SC_PREFIX/bin/apply.sh. Change the time with: syscheck set schedule HH:MM
[Unit]
Description=Run syscheck every day at $SC_SCHEDULE

[Timer]
OnCalendar=*-*-* $(printf '%02d:%02d' "$((10#$hh))" "$((10#$mm))"):00
Persistent=true

[Install]
WantedBy=timers.target
U
else
  echo "apply: SC_SCHEDULE='$SC_SCHEDULE' is not HH:MM; schedule left unchanged" >&2; fail=1
fi
chmod 0644 "$UNIT/syscheck.service" "$UNIT/syscheck.timer" 2>/dev/null
systemctl daemon-reload 2>/dev/null
if [ "${SC_ENABLED:-on}" = "on" ]; then
  systemctl enable --quiet syscheck.timer 2>/dev/null || { echo "apply: could not enable syscheck.timer" >&2; fail=1; }
  systemctl restart syscheck.timer 2>/dev/null || true
else
  systemctl disable --now --quiet syscheck.timer 2>/dev/null || true
fi

# --- sudoers ------------------------------------------------------------------
# The analysis account may run exactly two root-owned scripts without a
# password: the read-only diagnostics wrapper and the check itself.
SUDO=/etc/sudoers.d/99-syscheck
if id "$SC_USER" >/dev/null 2>&1 && [ "$(id -u "$SC_USER")" != "0" ]; then
  sed "s/@USER@/$SC_USER/g" "$SC_PREFIX/etc/syscheck.sudoers" > "$SUDO.tmp"
  chmod 0440 "$SUDO.tmp"
  if visudo -cqf "$SUDO.tmp" >/dev/null 2>&1; then
    mv -f "$SUDO.tmp" "$SUDO"
  else
    rm -f "$SUDO.tmp"; echo "apply: generated sudoers failed validation; left unchanged" >&2; fail=1
  fi
else
  echo "apply: account '$SC_USER' does not exist; no sudoers grant written" >&2; fail=1
fi

# --- login banner -------------------------------------------------------------
# Debian and Ubuntu print update-motd.d scripts at login. Elsewhere (Arch and
# others) a profile.d snippet prints it on interactive SSH logins instead.
rm -f /etc/update-motd.d/99-syscheck /etc/profile.d/syscheck-banner.sh
if [ "${SC_BANNER:-on}" = "on" ]; then
  if [ -d /etc/update-motd.d ]; then
    install -m 0755 -o root -g root "$SC_PREFIX/etc/99-syscheck" /etc/update-motd.d/99-syscheck
  elif [ -d /etc/profile.d ]; then
    install -m 0644 -o root -g root "$SC_PREFIX/etc/syscheck-banner.sh" /etc/profile.d/syscheck-banner.sh
  fi
fi

[ -d /etc/logrotate.d ] && install -m 0644 -o root -g root "$SC_PREFIX/etc/syscheck.logrotate" /etc/logrotate.d/syscheck
ln -sfn "$SC_PREFIX/bin/syscheck" /usr/local/bin/syscheck

# --- state directory ----------------------------------------------------------
# Root-only for writing. Each run directory is handed to the analysis account
# for the duration of the analysis by run.sh, and taken back afterwards.
mkdir -p "$SC_VAR/runs" "$SC_ETC"
chown root:root "$SC_VAR" "$SC_VAR/runs" "$SC_ETC"
chmod 0755 "$SC_VAR" "$SC_VAR/runs" "$SC_ETC"
for f in "$SC_VAR"/*.tsv "$SC_VAR"/state.json "$SC_VAR"/motd "$SC_VAR"/run.lock; do
  [ -f "$f" ] && [ ! -L "$f" ] && { chown root:root "$f"; chmod 0644 "$f"; }
done
# Earlier versions kept a group-writable alarm pid file here.
rm -f "$SC_VAR/alarm.pid"
touch /var/log/syscheck.log && chown root:adm /var/log/syscheck.log 2>/dev/null; chmod 0640 /var/log/syscheck.log

# Re-render the banner so a settings change shows at the next login.
[ -f "$SC_STATE" ] && "$SC_PREFIX/bin/motd-render.sh" > "$SC_MOTD.tmp" 2>/dev/null \
  && chmod 0644 "$SC_MOTD.tmp" && mv -f "$SC_MOTD.tmp" "$SC_MOTD"
rm -f "$SC_MOTD.tmp"

exit "$fail"
