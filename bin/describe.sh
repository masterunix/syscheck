#!/usr/bin/env bash
# Print a starting description of THIS machine for Claude, in Markdown.
# install.sh saves it as /etc/syscheck/machine.md, which stays on this machine.
# Edit that file (`syscheck describe --edit`) to say what the machine is for:
# Claude reads it at the top of every analysis.
set -uo pipefail
SC_PREFIX="${SC_PREFIX:-/opt/syscheck}"
. "$SC_PREFIX/lib/common.sh"

dmi() { cat "/sys/class/dmi/id/$1" 2>/dev/null | tr -s ' ' | sed 's/^ //;s/ $//'; }
vendor="$(dmi sys_vendor)"; product="$(dmi product_name)"; version="$(dmi product_version)"
chassis_type="$(dmi chassis_type)"
case "$chassis_type" in
  8|9|10|14|31|32) form="laptop" ;;
  3|4|5|6|7|13|15|16|35|36) form="desktop" ;;
  17|23|28) form="server" ;;
  *) form="computer" ;;
esac
cpu="$(lscpu 2>/dev/null | awk -F: '/^Model name/{sub(/^ +/,"",$2); print $2; exit}')"
cores="$(nproc 2>/dev/null)"
ram_gb="$(awk '/MemTotal/{printf "%.0f", $2/1048576}' /proc/meminfo)"
os="$(. /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-Linux}")"
bios_date="$(dmi bios_date)"

disks="$(lsblk -dno NAME,SIZE,ROTA,TYPE,MODEL 2>/dev/null | awk '$4=="disk" && $1 !~ /^(loop|zram|sr)/ {
  kind = ($3=="1") ? "spinning hard disk" : "solid-state"
  model=""; for (i=5;i<=NF;i++) model = model (i>5?" ":"") $i
  printf "  - `/dev/%s`: %s %s, %s\n", $1, $2, kind, (model==""?"model unknown":model) }')"
ndisks="$(printf '%s\n' "$disks" | grep -c '^  - ')"

services=""
for s in nginx apache2 caddy docker containerd postgresql mysql mariadb redis-server \
         plexmediaserver jellyfin ollama smbd nfs-server tailscaled cloudflared \
         wg-quick@wg0 home-assistant k3s libvirtd lxd snap.lxd.daemon; do
  systemctl is-active --quiet "$s" 2>/dev/null && services="$services $s"
done
pg="$(systemctl list-units --type=service --state=active --no-legend --plain 'postgresql@*' 2>/dev/null | awk '{print $1; exit}')"
[ -n "$pg" ] && services="$services ${pg%.service}"
ctr=""
command -v docker >/dev/null && ctr="$(timeout 10 docker ps --format '{{.Names}}' 2>/dev/null | head -15 | paste -sd, - | sed 's/,/, /g')"

cat <<M
<!--
  What Claude is told about this machine at the start of every analysis.
  Generated by syscheck on $(date +%F). It stays on this machine and is never
  uploaded or shipped with syscheck. Edit it freely: say what the machine is
  for, what matters most, and anything odd that is known and expected.
-->

A ${vendor:+$vendor }${product:-$form}${version:+ ($version)}, a $form running $os.

- CPU: ${cpu:-unknown} (${cores:-?} threads)
- RAM: ${ram_gb:-?} GB
- Firmware date: ${bios_date:-unknown}
- Storage ($ndisks disk$([ "$ndisks" = 1 ] || echo s)):
$disks
- Root filesystem: \`$SC_ROOT_DEV\` on \`$SC_DISK\`$([ "$ndisks" = 1 ] && echo ". It is the only disk: there is no RAID or second copy on this machine, so when it fails the data goes with it.")
- Services running at install time:${services:- none of the common server daemons were detected}
${ctr:+- Docker containers: $ctr}

## What this machine is for

(Not filled in yet. Replace this line with what the machine does and what
would hurt most if it failed. Until then, judge severity from the evidence.)
M
